/**
 * Measures how each bot profile shows up in the HUD (VPIP, PFR, ...) in the SPC satellite, for the
 * research bot that guesses opponents' styles from their stats. Writes src/research/profileRates.ts.
 *
 *   npx tsx scripts/gen-profile-rates.ts 300
 */
import { writeFileSync } from 'node:fs';
import { emptyCounts, type StatCounts } from '../src/analysis/handFlags';
import { PROFILES, type ProfileKey } from '../src/bots/profiles';
import { fieldReg } from '../src/research/policies';
import { RATE_STATS } from '../src/research/rateStats';
import { satelliteConfig } from '../src/research/sim';
import { makeRng } from '../src/engine/rng';
import { Tournament } from '../src/tournament/tournament';

const runs = Number(process.argv[2] ?? 300);
const pooled = new Map<ProfileKey, StatCounts>();
for (let seed = 1; seed <= runs; seed++) {
  const t = new Tournament(satelliteConfig('beginning', 100000 + seed));
  const rng = makeRng(seed);
  // play to the end even after the hero busts, so every stage is sampled: the hero folds once out
  while (!t.finished && !t.heroOut) {
    const s = t.startRound();
    if (!s) break;
    while (!s.done) { t.runBots(); if (t.isHeroTurn()) t.heroAct(fieldReg.act(t, s, rng)); }
    t.finishRound();
    t.history.length = 0;
  }
  for (const [id, c] of t.hud) {
    const prof = t.profileOf(id);
    if (prof === 'hero') continue;
    const acc = pooled.get(prof) ?? emptyCounts();
    for (const k of Object.keys(acc) as (keyof StatCounts)[]) acc[k] += c[k];
    pooled.set(prof, acc);
  }
}
const rates: Record<string, number[]> = {};
for (const p of Object.keys(PROFILES) as ProfileKey[]) {
  const c = pooled.get(p) ?? emptyCounts();
  rates[p] = RATE_STATS.map((st) => {
    const n = st.den(c), x = st.num(c);
    return Math.round(((x + 1) / (n + 2)) * 1000) / 1000;
  });
  console.log(p.padEnd(8), c.hands, rates[p].join(' '));
}
writeFileSync('src/research/profileRates.ts', `/** Generated by scripts/gen-profile-rates.ts (${runs} satellites): each profile's rate for each RATE_STATS entry. */
import type { ProfileKey } from '../bots/profiles';

export const PROFILE_RATES: Record<ProfileKey, number[]> = ${JSON.stringify(rates, null, 2)};
`);
